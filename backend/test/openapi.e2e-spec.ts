/**
 * **Proving the gate in its other state**, which is the only way the default is
 * worth anything. A production deployment that says nothing serves neither
 * route, and the API itself is untouched by their absence.
 */
describe('API documentation, disabled (e2e)', () => {
  let app: INestApplication<App>;

  beforeAll(async () => {
    process.env[SWAGGER_ENABLED_KEY] = 'false';

    app = await bootApplication();
  });

  afterAll(async () => {
    delete process.env[SWAGGER_ENABLED_KEY];
    await app.close();
  });

  it('does not serve the UI', () =>
    request(app.getHttpServer()).get(SWAGGER_DOCS_ROUTE).expect(404));

  it('does not serve the raw document', () =>
    request(app.getHttpServer()).get(SWAGGER_JSON_ROUTE).expect(404));

  it('does not serve the UI assets', () =>
    request(app.getHttpServer())
      .get(`${SWAGGER_DOCS_ROUTE}/swagger-ui-bundle.js`)
      .expect(404));

  /**
   * The 404 is the ordinary Feature 033 envelope from `AllExceptionsFilter`,
   * not a bare Express page — which is what proves the route genuinely does not
   * exist rather than being served and refused.
   */
  it('renders the refusal as the standard error envelope', async () => {
    const response = await request(app.getHttpServer())
      .get(SWAGGER_DOCS_ROUTE)
      .expect(404);

    expect(response.body).toEqual({
      success: false,
      statusCode: 404,
      message: expect.any(String) as unknown as string,
      path: SWAGGER_DOCS_ROUTE,
      timestamp: expect.any(String) as unknown as string,
    });
  });

  /** The application is otherwise exactly the application. */
  it('serves the API unchanged', () =>
    request(app.getHttpServer())
      .get(`${API_BASE_PATH}/health`)
      .expect(200)
      .expect({ success: true, data: { status: 'ok', service: 'backend' } }));

  /** And with the strict policy, since nothing relaxed it. */
  it('serves the strict policy everywhere', async () => {
    const response = await request(app.getHttpServer())
      .get(`${API_BASE_PATH}/health`)
      .expect(200);

    expect(response.headers['content-security-policy']).not.toContain(
      'unsafe-inline',
    );
  });
});
